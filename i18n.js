  const DICT = { ko, en };
  const KEY = 'llama.lang';
  function initial() {
    try {
      const saved = JSON.parse(localStorage.getItem(KEY));
      if (saved === 'ko' || saved === 'en') return saved;
    } catch (e) { /* 무시 */ }
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'ko';
    return /^ko/i.test(nav) ? 'ko' : 'en';
  }
  let lang = initial();

  function t(key, p) {
    const s = DICT[lang][key] != null ? DICT[lang][key] : (ko[key] != null ? ko[key] : key);
    if (!p) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (p[k] != null ? p[k] : ''));
  }

  function applyStatic() {
    document.documentElement.lang = lang;
    document.title = t('doc.title');
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
    document.querySelectorAll('[data-lang]').forEach((el) => { el.setAttribute('aria-pressed', String(el.dataset.lang === lang)); });
  }

